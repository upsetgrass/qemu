// 通用映射函数
static const char *id2name(const name_map *map, int max, const unsigned int id) {
    for (int i = 0; i < max; i++) {
        if (map[i].id == id) {
            return map[i].name;
        }
    }
    return NULL;
}

const char *RISCV_insn_name(csh handle, unsigned int id) {
    if (id >= RISCV_INS_ENDING)
        return NULL;
    return id2name(riscv_insn_name_maps, sizeof(riscv_insn_name_maps) / sizeof(riscv_insn_name_maps[0]), id);
}
